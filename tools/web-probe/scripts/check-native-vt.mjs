import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {loadNativeVt} from '../native-vt.js';
const bytes = await readFile(new URL('../../../.deps/ghostty-vt-wasm32-freestanding/bin/ghostty-vt.wasm', import.meta.url));
const host = await loadNativeVt(bytes);
assert.throws(()=>host.create(20,3,{foreground:-1}),RangeError);
assert.throws(()=>host.create(20,3,{scrollback:2**32}),RangeError);
const configured=host.create(20,3,{foreground:0xdcdfe6,background:0x12141a,scrollback:0});
try {
  configured.write('configured');
  const frame=configured.snapshot();
  assert.deepEqual(frame.background,[18,20,26]);
  assert.deepEqual(frame.rows[0][1][0][2],[220,223,230]);
  configured.write('\x1b]11;#223344\x07');
  assert.deepEqual(configured.snapshot().background,[34,51,68]);
  configured.write('\x1b]111\x07');
  assert.deepEqual(configured.snapshot().background,[18,20,26],'OSC reset restores configured defaults');
  configured.write('\r\n'.repeat(100));
  assert.equal(configured.snapshot().scrollback_lines,0,'zero limit disables retained history');
} finally { configured.dispose(); }
const first = host.create(5,4), second = host.create(20,4);
try {
  first.write('abcdefghij\r\nnext');
  assert.equal(first.selectedText(), null);
  first.selectAll();
  assert.equal(first.selectedText(), 'abcdefghij\nnext');
  assert.equal(first.selectedText(100, false), 'abcde\nfghij\nnext');
  assert.throws(() => first.selectedText(3));
  second.write('hello 世界');
  second.selectAll();
  assert.equal(second.selectedText(), 'hello 世界');
  const encode = (key, options) => new TextDecoder().decode(second.encode(key, options));
  assert.equal(encode('ENTER'), '\r');
  assert.equal(encode('C', {control:true, text:'c'}), '\x03');
  assert.equal(encode('U', {control:true, text:'u'}), '\x15');
  assert.equal(encode('A', {alt:true, text:'a'}), '\x1ba');
  assert.equal(encode('ARROW_UP'), '\x1b[A');
  second.write('\x1b[?1h');
  assert.equal(encode('ARROW_UP'), '\x1bOA');
  assert.equal(new TextDecoder().decode(first.encode('ARROW_UP')), '\x1b[A');
  second.write('\x1b[?1l\x1b[>11u');
  for (const [action, expected] of [['PRESS','\x1b[97u'],['REPEAT','\x1b[97;1:2u'],['RELEASE','\x1b[97;1:3u']]) {
    assert.equal(encode('A', {action, text:'a'}), expected);
  }
  assert.equal(encode('UNIDENTIFIED', {text:'é'}), '\x1b[233u');
  second.write('\x1b[<u');
  assert.equal(encode('A', {action:'RELEASE', text:'a'}), '');
  assert.throws(() => encode('NOT_A_KEY'));
  first.clearSelection();
  assert.equal(first.selectedText(), null);
  assert.equal(second.selectedText(), 'hello 世界');
} finally { first.dispose(); second.dispose(); }
first.dispose();
assert.throws(() => first.write('after disposal'));
const rendered=host.create(20,4);
try {
  assert.equal(rendered.snapshot().rows.length,4);
  assert.equal(rendered.snapshot().rows.length,0,'idle frames have no cell payload');
  rendered.write('\x1b[31mred\x1b[0m 世界 e\u0301');
  const patch=rendered.snapshot(), row=patch.rows[0][1];
  assert.equal(patch.rows.length,1);
  assert.equal(row.slice(0,3).map(c=>c[0]).join(''),'red');
  assert.notDeepEqual(row[0][2],row[3][2]);
  assert.equal(row[4][0],'世'); assert.equal(row[4][1],2); assert.equal(row[5][1],0);
  assert.equal(row[9][0],'e\u0301');
  rendered.selectAll();
  assert.ok(rendered.snapshot().selections.some(([,range])=>range!==null));
  rendered.clearSelection();
  assert.ok(rendered.snapshot().selections.every(([,range])=>range===null));
  rendered.write('\x1b[2J\x1b[H\x1b[4:3;58:2::12:34:56;53mX\x1b[0m');
  const styled=rendered.snapshot().rows[0][1][0];
  assert.equal(styled[0],'X'); assert.ok(styled[4]&4);
  assert.deepEqual(styled[5],[12,34,56]); assert.equal(styled[6],true); assert.equal(styled[7],true);
  rendered.resize(30,6);
  const resized=rendered.snapshot();
  assert.equal(resized.columns,30); assert.equal(resized.height,6);
  assert.equal(resized.rows.length,6);
} finally { rendered.dispose(); }
const gestures=host.create(20,4);
try {
  gestures.write('abcdef\r\nuvwxyz');
  const select=(action,column,row,rectangle=false,clicks=1)=>gestures.select(action,column*8.5,row*20,8.5,20,20,4,rectangle,clicks);
  select('PRESS',1,0); select('DRAG',4,0);
  assert.equal(gestures.selectedText(),'bcd');
  select('DRAG',4,1,true); select('RELEASE',4,1,true);
  assert.equal(gestures.selectedText(),'bcd\nvwx');
  select('PRESS',2,0,false,2);
  assert.equal(gestures.selectedText(),'abcdef');
  select('PRESS',2,1,false,3);
  assert.equal(gestures.selectedText(),'uvwxyz');
} finally { gestures.dispose(); }
const history=host.create(20,3);
try {
  history.write(Array.from({length:12},(_,i)=>`line-${i}\r\n`).join(''));
  const bottom=history.snapshot();
  assert.ok(bottom.scrollback_lines>0);
  assert.equal(bottom.scrollback_offset,0);
  history.scroll('DELTA',-2);
  assert.equal(history.snapshot().scrollback_offset,2);
  history.scroll('TOP');
  const top=history.snapshot();
  assert.equal(top.scrollback_offset,top.scrollback_lines);
  assert.equal(top.rows[0][1].map(c=>c[0]).join(''),'line-0');
  history.scroll('ROW',4);
  const absolute=history.snapshot();
  assert.equal(absolute.scrollback_offset,absolute.scrollback_lines-4);
  history.scroll('ROW',4);
  assert.equal(history.snapshot().scrollback_offset,absolute.scrollback_offset,'absolute drags do not accumulate');
  history.scroll('TOP');
  history.select('PRESS',12,0,8,20,20,3,false,3);
  assert.equal(history.selectedText(),'line-0');
  history.scroll('BOTTOM');
  assert.equal(history.snapshot().scrollback_offset,0);
  const select=(action,y)=>history.select(action,12,y,8,20,20,3,false,1);
  assert.equal(select('PRESS',20),false);
  assert.equal(select('DRAG',-20),true,'drag above viewport requests scheduled ticks');
  let active=true, ticks=0;
  while (active && ticks++<100) active=select('AUTOSCROLL_TICK',-20);
  assert.equal(active,false,'ticks stop at oldest history');
  const scrolled=history.snapshot();
  assert.equal(scrolled.scrollback_offset,scrolled.scrollback_lines);
  assert.ok(history.selectedText().includes('line-1'),'selection extends into history');
  assert.equal(select('DRAG',20),false,'returning inside cancels scheduling');
  assert.equal(select('DRAG',90),true,'drag below viewport scrolls toward live output');
  active=true; ticks=0;
  while (active && ticks++<100) active=select('AUTOSCROLL_TICK',90);
  assert.equal(active,false);
  assert.ok(history.snapshot().scrollback_offset<scrolled.scrollback_offset,'ticks move down toward live output');
  assert.equal(select('RELEASE',90),false);
} finally { history.dispose(); }
console.log('Pinned native VT WASM: selection gestures/copy, keyboard modes and sparse styled snapshots passed.');
