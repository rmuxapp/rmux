import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Ghostty} from '../dist/ghostty-web.js';
import {createHost} from '../dist/engine.js';
const wasm = await readFile(new URL('../dist/ghostty-vt.wasm',import.meta.url));
const host = createHost(await Ghostty.load('data:application/wasm;base64,'+wasm.toString('base64')));
const first = host.create(20,4), second = host.create(20,4);
const snap = id => JSON.parse(host.snapshot(id));
assert.equal(snap(first).rows.length,4);
assert.equal(snap(first).rows.length,0,'idle snapshots must not transfer cells');
host.write(first,'\x1b[31mred\x1b[0m\r\nold');
const update = snap(first);
assert.equal(update.rows[0][1].slice(0,3).map(c=>c.text).join(''),'red');
assert.notDeepEqual(update.rows[0][1][0].foreground,update.rows[1][1][0].foreground);
assert.ok(update.rows.length < 4,'only dirty rows should cross into Rust');
assert.ok(snap(second).rows.every(([,cells])=>cells.every(c=>!c.text.trim())),'panes remain isolated');
host.write(first,'\x1b[2J\x1b[Hnew');
const cleared = snap(first);
assert.ok(cleared.rows.find(([y])=>y===1)[1].every(c=>!c.text.trim()),'clear removes previous output');
host.free(first); host.free(second);
const reused = host.create(20,4);
assert.ok(snap(reused).rows.every(([,cells])=>cells.every(c=>!c.text.trim())),'reused WASM memory starts clear');
host.free(reused);
console.log('Sparse updates, styles, pane isolation, clear and recreation passed.');
const sized = host.create(40,8);
host.write(sized,'left marker\r\nright marker');
snap(sized);
for (const [columns,height] of [[20,4],[80,24],[1,1],[40,8]]) {
  host.resize(sized,columns,height);
  const frame = snap(sized);
  assert.equal(frame.columns,columns);
  assert.equal(frame.height,height);
  assert.equal(frame.rows.length,height,'resizes replace all cached rows');
  assert.ok(frame.rows.every(([,cells])=>cells.length===columns));
  host.resize(sized,columns,height);
  assert.equal(snap(sized).rows.length,0,'unchanged geometry stays clean');
}
host.free(sized);
console.log('Resize dimensions, full invalidation and unchanged-size no-op passed.');
