//! Resolve shared symbolic keys through the pinned engine ABI manifest.
use rmux_core::keyboard::Key;
pub fn name(key: Key) -> String {
    match key {
        Key::Enter => "ENTER".into(),
        Key::Backspace => "BACKSPACE".into(),
        Key::Tab => "TAB".into(),
        Key::Escape => "ESCAPE".into(),
        Key::ArrowUp => "ARROW_UP".into(),
        Key::ArrowDown => "ARROW_DOWN".into(),
        Key::ArrowLeft => "ARROW_LEFT".into(),
        Key::ArrowRight => "ARROW_RIGHT".into(),
        Key::Home => "HOME".into(),
        Key::End => "END".into(),
        Key::Insert => "INSERT".into(),
        Key::Delete => "DELETE".into(),
        Key::PageUp => "PAGE_UP".into(),
        Key::PageDown => "PAGE_DOWN".into(),
        Key::Space => "SPACE".into(),
        Key::BracketLeft => "BRACKET_LEFT".into(),
        Key::BracketRight => "BRACKET_RIGHT".into(),
        Key::Backslash => "BACKSLASH".into(),
        Key::Slash => "SLASH".into(),
        Key::Minus => "MINUS".into(),
        Key::Equal => "EQUAL".into(),
        Key::Backquote => "BACKQUOTE".into(),
        Key::Semicolon => "SEMICOLON".into(),
        Key::Quote => "QUOTE".into(),
        Key::Comma => "COMMA".into(),
        Key::Period => "PERIOD".into(),
        Key::Digit0 => "DIGIT_0".into(),
        Key::Digit1 => "DIGIT_1".into(),
        Key::Digit2 => "DIGIT_2".into(),
        Key::Digit3 => "DIGIT_3".into(),
        Key::Digit4 => "DIGIT_4".into(),
        Key::Digit5 => "DIGIT_5".into(),
        Key::Digit6 => "DIGIT_6".into(),
        Key::Digit7 => "DIGIT_7".into(),
        Key::Digit8 => "DIGIT_8".into(),
        Key::Digit9 => "DIGIT_9".into(),
        Key::Letter(index) => char::from(b'A' + index).to_string(),
        Key::Function(number) => format!("F{number}"),
        Key::Character(_) => "UNIDENTIFIED".into(),
    }
}
