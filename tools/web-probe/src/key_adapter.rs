//! Adapter for pinned ghostty-web 0.4.0 Key values from index.d.ts.
//! Numeric values differ from native C API; never cast shared keys.
use rmux_core::keyboard::Key;
pub fn code(key: Key) -> u32 {
    match key {
        Key::Enter => 58,
        Key::Backspace => 53,
        Key::Tab => 64,
        Key::Escape => 120,
        Key::ArrowUp => 78,
        Key::ArrowDown => 75,
        Key::ArrowLeft => 76,
        Key::ArrowRight => 77,
        Key::Home => 71,
        Key::End => 69,
        Key::Insert => 72,
        Key::Delete => 68,
        Key::PageUp => 74,
        Key::PageDown => 73,
        Key::Space => 63,
        Key::BracketLeft => 3,
        Key::BracketRight => 4,
        Key::Backslash => 2,
        Key::Slash => 50,
        Key::Minus => 46,
        Key::Equal => 16,
        Key::Backquote => 1,
        Key::Semicolon => 49,
        Key::Quote => 48,
        Key::Comma => 5,
        Key::Period => 47,
        Key::Digit0 => 6,
        Key::Digit1 => 7,
        Key::Digit2 => 8,
        Key::Digit3 => 9,
        Key::Digit4 => 10,
        Key::Digit5 => 11,
        Key::Digit6 => 12,
        Key::Digit7 => 13,
        Key::Digit8 => 14,
        Key::Digit9 => 15,
        Key::Letter(index) => 20 + u32::from(index),
        Key::Function(number) => 121 + u32::from(number) - 1,
        Key::Character(_) => 0,
    }
}
