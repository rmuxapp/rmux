//! Stable command identities and display names shared by application hosts.
//! Hosts decide availability and implement dispatch; listing a command does not
//! imply its platform service exists (for example SSH in the static browser demo).
macro_rules! commands {
    ($($id:ident => $title:literal),* $(,)?) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum CommandId { $($id),* }
        impl CommandId {
            pub const ALL: &'static [Self] = &[$(Self::$id),*];
            pub const fn title(self) -> &'static str {
                match self { $(Self::$id => $title),* }
            }
        }
    };
}
